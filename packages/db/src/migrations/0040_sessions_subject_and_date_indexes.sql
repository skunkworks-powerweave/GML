-- Index the classroom-session log by subject, and by date alone (F143).
--
-- ── WHY ──────────────────────────────────────────────────────────────────────
--
-- sessions carried (school_id, date), (teacher_id, date) and (class_id, date),
-- and nothing leading with subject_id or with the date. So:
--   /repo/subjects      a correlated COUNT(*) per subject -- a full scan of
--                       sessions for every subject, on every load;
--   /repo/subject/[id]  its latest 8, top teachers and total -- each a full
--                       scan, the first two with a sort;
--   /repo/sessions      ?subject= filters on it, and the unfiltered default,
--                       ORDER BY scheduled_date DESC, scheduled_time DESC
--                       LIMIT 200, sorted the entire table.
-- At ~98 schools logging weekly sessions the table grows by 100k+ rows a year.
-- On a 350k-row copy the per-subject counts took 338 ms and the latest-8 57 ms;
-- with (subject_id, scheduled_date) they took 42 ms and 0.1 ms.
--
-- Generated by drizzle-kit from the declarations in schema/sessions.ts, with
-- IF NOT EXISTS added for the escape hatch below.
--
-- ── NOT CONCURRENTLY, DELIBERATELY ───────────────────────────────────────────
--
-- The drizzle migrator runs this inside a transaction, where CREATE INDEX
-- CONCURRENTLY cannot run (see 0018 and 0028). The cost is a SHARE lock that
-- blocks session writes while each index builds -- milliseconds at today's row
-- count. On an already-large sessions table, build both by hand first with
-- CREATE INDEX CONCURRENTLY IF NOT EXISTS (same names and columns) and this
-- file finds them present and does nothing.

CREATE INDEX IF NOT EXISTS "sessions_subject_date_idx" ON "sessions" USING btree ("subject_id","scheduled_date");--> statement-breakpoint
CREATE INDEX IF NOT EXISTS "sessions_date_time_idx" ON "sessions" USING btree ("scheduled_date","scheduled_time");
